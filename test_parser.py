def run():
    bad = 0
    for name, text, expect in SAMPLES:
        o = parse_order(text)
        if o is None:
            print(f"FAIL {name}: None")
            bad += 1
            continue
        d = o.to_dict()
        errs = [f"{k}: ждали {v!r}, получили {d[k]!r}" for k, v in expect.items() if d[k] != v]
        print(("OK  " if not errs else "FAIL"), name, "" if not errs else "; ".join(errs))
        bad += bool(errs)
    from order_parser import split_multi
    n_parts = len(split_multi('30.10 22.00 Ростов Алушта 18 000 + платка\n\n31.10 05.00  Самара Саратов 10 000\n\n31.10 13.00  Аргун ( Чеченская Республика) Махачкала 4500\n\n31.10 21.30 Минеральный Воды Волгоград минивэн 23 000\n\nПо заказам писать\nсюда 👉Междугороднее такси'))
    print("OK  " if n_parts == 4 else "FAIL", "список из 4 заказов в одном сообщении ->", n_parts)
    bad += n_parts != 4
    print("OK  " if len(split_multi("30.10 22.00 Ростов Алушта 17000")) == 1 else "FAIL", "одиночное сообщение не делится")
    for name, text in NOT_ORDERS:
        o = parse_order(text)
        print(("OK  " if o is None else "FAIL"), "не заказ:", name,
              "" if o is None else f"-> {o.from_city} / {o.to_city} / {o.price}")
        bad += o is not None
    print("\nПровалено:", bad)
    return bad


if __name__ == "__main__":
    raise SystemExit(run())
