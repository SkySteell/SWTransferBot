from datetime import datetime, timedelta, timezone

from cards import head_line
from order_parser import parse_order

TZ = timezone(timedelta(hours=3))
NOW = datetime(2026, 11, 5, 14, 30, tzinfo=TZ)
bad = 0


def check(name, text, want, now=NOW):
    global bad
    o = parse_order(text, allow_unrouted=True)
    got = head_line(o, now)
    ok = got == want
    bad += not ok
    print("OK  " if ok else "FAIL", name, "->", got, "" if ok else f"| ждали {want!r}")


check("сегодня с временем", "Сегодня 17:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11 17:00")
check("завтра с временем", "Завтра в 9:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · завтра 06.11 09:00")
check("послезавтра: только дата и время", "Послезавтра 12:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · 07.11 12:00")
check("дальше: дата и время", "10.11 08:30 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · 10.11 08:30")
check("только время, ещё не прошло", "17:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11 17:00")
check("только время, уже прошло -> завтра", "07:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · завтра 06.11 07:00")
check("срочный без времени", "Сейчас Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11 · ⚡️ СРОЧНО")
check("срочный с временем", "Срочно 16:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11 16:00 · ⚡️ СРОЧНО")
check("через 30 минут", "Через 30 мин Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11 15:00")
check("через 3 часа за полночь", "Через 3 часа Ростов - Таганрог 2000", "🆕 ЗАКАЗ · завтра 06.11 02:00",
      now=datetime(2026, 11, 5, 23, 0, tzinfo=TZ))
check("только дата", "05.11 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · сегодня 05.11")
check("только «завтра»", "Завтра Ростов - Таганрог 2000", "🆕 ЗАКАЗ · завтра 06.11")
check("прошедшая дата", "30.10 22:00 Ростов - Таганрог 2000", "🆕 ЗАКАЗ · 30.10 22:00")
check("даты нет вообще", "Ростов - Таганрог 2000 сегодня", "🆕 ЗАКАЗ · сегодня 05.11")
check("ничего про время", "Ростов - Таганрог 2000 на руки", "🆕 ЗАКАЗ · -")
print("\nПровалено:", bad)
raise SystemExit(bad)
